package com.example.cinemahub.service;

import com.example.cinemahub.model.Promotion;
import java.math.BigDecimal;
import java.time.LocalDateTime;
import java.util.*;

/** Shared by management, online quotes, online holds and counter sales. */
public final class PromotionRules {
    private PromotionRules() {}
    public static String code(String value) {
        String code = value == null ? "" : value.trim().toUpperCase(Locale.ROOT);
        if (!code.matches("[A-Z0-9_-]{1,64}")) throw new IllegalArgumentException("Mã khuyến mãi không hợp lệ");
        return code;
    }
    public static void validate(Promotion p) {
        p.setCode(code(p.getCode()));
        if (p.getTitle() == null || p.getTitle().isBlank() || p.getTitle().length() > 200)
            throw new IllegalArgumentException("Tiêu đề phải có từ 1 đến 200 ký tự");
        p.setTitle(p.getTitle().trim());
        String type = Objects.toString(p.getDiscountType(), "").toUpperCase(Locale.ROOT);
        if (type.equals("FIXED") || type.equals("FIXED_AMOUNT")) p.setDiscountType("Fixed");
        else if (type.equals("PERCENTAGE")) p.setDiscountType("Percentage");
        else throw new IllegalArgumentException("Loại giảm giá không hợp lệ");
        if (p.getDiscountValue() == null) throw new IllegalArgumentException("Thiếu giá trị giảm giá");
        Money.vnd(p.getDiscountValue());
        if (type.equals("PERCENTAGE") && p.getDiscountValue() > 100)
            throw new IllegalArgumentException("Phần trăm giảm giá phải từ 0 đến 100");
        if (!type.equals("PERCENTAGE") && p.getDiscountValue() != Money.vnd(p.getDiscountValue()))
            throw new IllegalArgumentException("Giảm giá cố định phải là số nguyên VND");
        if (p.getStartDate() == null || p.getEndDate() == null || !p.getEndDate().isAfter(p.getStartDate()))
            throw new IllegalArgumentException("Ngày kết thúc phải sau ngày bắt đầu");
        if (!Set.of("Active", "Disabled", "Used").contains(Objects.toString(p.getStatus(), "")))
            throw new IllegalArgumentException("Trạng thái khuyến mãi không hợp lệ");
        if (p.getConditions() != null) for (var entry : p.getConditions().entrySet()) {
            switch (entry.getKey()) {
                case "minSpend", "maxDiscount" -> amount(entry.getValue());
                case "usageLimit", "perUserLimit" -> {
                    double n = amount(entry.getValue());
                    if (n != Math.floor(n)) throw new IllegalArgumentException("Giới hạn lượt dùng phải là số nguyên");
                }
                // These conditions are generated by the membership subsystem, not editable in management.
                case "redeemedByUserId", "rewardVoucherId" -> {
                    if (!(entry.getValue() instanceof String s) || s.isBlank())
                        throw new IllegalArgumentException("Điều kiện voucher không hợp lệ");
                }
                default -> throw new IllegalArgumentException("Điều kiện chưa được hỗ trợ: " + entry.getKey());
            }
        }
        if (p.getBannerImage() != null && !p.getBannerImage().isBlank()
                && !p.getBannerImage().matches("https?://[^\\s]{1,2000}"))
            throw new IllegalArgumentException("Ảnh banner phải là URL HTTP hoặc HTTPS");
    }
    public static double amount(Object value) {
        try {
            double n = new BigDecimal(Objects.toString(value, "")).doubleValue();
            if (n != Money.vnd(n)) throw new IllegalArgumentException("Điều kiện phải là số nguyên");
            return n;
        } catch (RuntimeException ex) { throw new IllegalArgumentException("Giá trị điều kiện không hợp lệ"); }
    }
    public static double discount(Promotion p, double subtotal, String userId) {
        validate(p);
        double base = Money.vnd(subtotal);
        Map<String, Object> c = p.getConditions() == null ? Map.of() : p.getConditions();
        if (c.containsKey("redeemedByUserId") && !Objects.equals(c.get("redeemedByUserId"), userId))
            throw new IllegalArgumentException("Voucher chỉ dành cho tài khoản đã đổi điểm");
        if (base < amount(c.getOrDefault("minSpend", 0)))
            throw new IllegalArgumentException("Đơn hàng chưa đạt giá trị tối thiểu của khuyến mãi");
        double discount = "Percentage".equals(p.getDiscountType())
                ? BigDecimal.valueOf(base).multiply(BigDecimal.valueOf(p.getDiscountValue())).movePointLeft(2).doubleValue()
                : p.getDiscountValue();
        if (c.containsKey("maxDiscount")) discount = Math.min(discount, amount(c.get("maxDiscount")));
        return Math.min(base, Money.vnd(discount));
    }
    public static boolean active(Promotion p, LocalDateTime now) {
        return "Active".equals(p.getStatus()) && p.getStartDate() != null && p.getEndDate() != null
                && !now.isBefore(p.getStartDate()) && now.isBefore(p.getEndDate());
    }
}
